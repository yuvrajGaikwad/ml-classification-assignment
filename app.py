"""Streamlit application for evaluating saved WDBC classification models.

The application never retrains models. It loads saved .joblib artifacts and
evaluates them on an uploaded CSV containing the 30 WDBC features plus diagnosis.
"""

from pathlib import Path

import joblib
import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns
import streamlit as st
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    matthews_corrcoef,
    precision_score,
    recall_score,
    roc_auc_score,
)

st.set_page_config(
    page_title="Breast Cancer Classification Dashboard",
    page_icon="🔬",
    layout="wide",
)

MODEL_DIR = Path("model")
TARGET_COLUMN = "diagnosis"

FEATURE_COLUMNS = [
    "radius_mean", "texture_mean", "perimeter_mean", "area_mean",
    "smoothness_mean", "compactness_mean", "concavity_mean",
    "concave_points_mean", "symmetry_mean", "fractal_dimension_mean",
    "radius_se", "texture_se", "perimeter_se", "area_se",
    "smoothness_se", "compactness_se", "concavity_se",
    "concave_points_se", "symmetry_se", "fractal_dimension_se",
    "radius_worst", "texture_worst", "perimeter_worst", "area_worst",
    "smoothness_worst", "compactness_worst", "concavity_worst",
    "concave_points_worst", "symmetry_worst", "fractal_dimension_worst",
]

MODELS = {
    "Logistic Regression": MODEL_DIR / "logistic_regression.joblib",
    "Decision Tree": MODEL_DIR / "decision_tree.joblib",
    "K-Nearest Neighbors (KNN)": MODEL_DIR / "knn.joblib",
    "Naive Bayes": MODEL_DIR / "naive_bayes.joblib",
    "Support Vector Machine (SVM)": MODEL_DIR / "svm.joblib",
}


def normalise_target(series: pd.Series) -> pd.Series:
    """Accept the assignment's numeric target or original UCI M/B labels."""
    if series.dtype == object or pd.api.types.is_string_dtype(series):
        cleaned = series.astype(str).str.strip().str.upper()
        mapped = cleaned.map({"B": 0, "M": 1, "0": 0, "1": 1})
    else:
        mapped = pd.to_numeric(series, errors="coerce")

    if mapped.isna().any():
        raise ValueError("The diagnosis column must contain only B/M or 0/1 values.")

    mapped = mapped.astype(int)
    if not set(mapped.unique()).issubset({0, 1}):
        raise ValueError("The diagnosis column must contain only B/M or 0/1 values.")
    return mapped


@st.cache_resource
def load_model(model_path: str):
    """Load a pre-trained model without fitting or modifying it."""
    return joblib.load(model_path)


def get_auc_scores(model, X: pd.DataFrame):
    """Return continuous positive-class scores for ROC AUC."""
    if hasattr(model, "predict_proba"):
        probabilities = model.predict_proba(X)
        return probabilities[:, 1]
    if hasattr(model, "decision_function"):
        return model.decision_function(X)
    raise AttributeError("Selected model does not provide probability or decision scores.")


def calculate_metrics(y_true, y_pred, y_score):
    """Calculate the six metrics required by the assignment."""
    return {
        "Accuracy": accuracy_score(y_true, y_pred),
        "AUC": roc_auc_score(y_true, y_score),
        "Precision": precision_score(y_true, y_pred, zero_division=0),
        "Recall": recall_score(y_true, y_pred, zero_division=0),
        "F1 Score": f1_score(y_true, y_pred, zero_division=0),
        "MCC": matthews_corrcoef(y_true, y_pred),
    }


st.title("🔬 Breast Cancer Classification Dashboard")
st.caption(
    "Evaluate five pre-trained machine learning classifiers on held-out WDBC test data. "
    "Malignant = 1 and Benign = 0."
)

st.info(
    "Upload the generated test_data.csv file. The application loads saved trained "
    "models from the model/ directory and does not retrain them on uploaded data."
)

with st.sidebar:
    st.header("Evaluation Controls")
    selected_model_name = st.selectbox(
        "Select Classification Model",
        options=list(MODELS.keys()),
    )
    uploaded_file = st.file_uploader(
        "Upload Test Dataset (CSV)",
        type=["csv"],
        help="CSV must contain all 30 WDBC input features and the diagnosis target column.",
    )

if uploaded_file is None:
    st.subheader("Required CSV Format")
    st.write(
        "The uploaded file must contain the 30 WDBC feature columns plus the "
        "`diagnosis` target column. Use the `test_data.csv` generated by `train_models.py`."
    )
    st.write("Choose a model and upload the test CSV from the sidebar to begin evaluation.")
    st.stop()

try:
    data = pd.read_csv(uploaded_file)
except Exception as exc:
    st.error(f"Unable to read the uploaded CSV: {exc}")
    st.stop()

# Allow an ID column if someone uploads a labelled WDBC-derived CSV, but never use it.
if "id" in data.columns:
    data = data.drop(columns=["id"])

missing_features = [column for column in FEATURE_COLUMNS if column not in data.columns]
if TARGET_COLUMN not in data.columns:
    missing_features.append(TARGET_COLUMN)

if missing_features:
    st.error(
        "The uploaded CSV is missing required columns: " + ", ".join(missing_features)
    )
    st.stop()

# Ignore unrelated extra columns, while preserving exact training feature order.
X_test = data[FEATURE_COLUMNS].copy()

if X_test.isnull().any().any():
    st.error("The uploaded feature data contains missing values. Please use a complete test CSV.")
    st.stop()

try:
    X_test = X_test.apply(pd.to_numeric, errors="raise")
    y_test = normalise_target(data[TARGET_COLUMN])
except (ValueError, TypeError) as exc:
    st.error(f"Invalid test data: {exc}")
    st.stop()

if y_test.nunique() < 2:
    st.error(
        "AUC requires both benign and malignant classes in the uploaded test dataset. "
        "Please upload the complete generated test_data.csv."
    )
    st.stop()

model_path = MODELS[selected_model_name]
if not model_path.exists():
    st.error(
        f"Saved model not found: {model_path}. Run train_models.py and ensure the model/ "
        "directory is committed to the repository."
    )
    st.stop()

try:
    model = load_model(str(model_path))
    y_pred = model.predict(X_test)
    y_score = get_auc_scores(model, X_test)
    metrics = calculate_metrics(y_test, y_pred, y_score)
except Exception as exc:
    st.error(f"Model evaluation failed: {exc}")
    st.stop()

st.success(
    f"Successfully evaluated {selected_model_name} on {len(X_test)} uploaded test samples."
)

st.subheader("Uploaded Dataset Preview")
st.dataframe(data.head(10), use_container_width=True)
st.caption(f"Rows: {len(data)} | Input features used: {len(FEATURE_COLUMNS)}")

st.subheader("Evaluation Metrics")
metric_columns = st.columns(6)
for column, (metric_name, metric_value) in zip(metric_columns, metrics.items()):
    column.metric(metric_name, f"{metric_value:.4f}")

st.caption(
    "Precision, Recall and F1 use Malignant (1) as the positive class. "
    "AUC uses the model's positive-class probability/decision score."
)

left, right = st.columns(2)

with left:
    st.subheader("Confusion Matrix")
    cm = confusion_matrix(y_test, y_pred, labels=[0, 1])
    fig, ax = plt.subplots(figsize=(5.5, 4.5))
    sns.heatmap(
        cm,
        annot=True,
        fmt="d",
        cmap="Blues",
        cbar=False,
        xticklabels=["Benign (0)", "Malignant (1)"],
        yticklabels=["Benign (0)", "Malignant (1)"],
        ax=ax,
    )
    ax.set_xlabel("Predicted Class")
    ax.set_ylabel("Actual Class")
    ax.set_title(f"{selected_model_name} Confusion Matrix")
    fig.tight_layout()
    st.pyplot(fig)
    plt.close(fig)

with right:
    st.subheader("Classification Report")
    report = classification_report(
        y_test,
        y_pred,
        labels=[0, 1],
        target_names=["Benign", "Malignant"],
        output_dict=True,
        zero_division=0,
    )
    report_df = pd.DataFrame(report).transpose()
    st.dataframe(
        report_df.style.format({
            "precision": "{:.4f}",
            "recall": "{:.4f}",
            "f1-score": "{:.4f}",
            "support": "{:.0f}",
        }),
        use_container_width=True,
    )

st.subheader("Prediction Summary")
summary = pd.DataFrame({
    "Actual": y_test.map({0: "Benign", 1: "Malignant"}),
    "Predicted": pd.Series(y_pred).map({0: "Benign", 1: "Malignant"}),
})
summary["Correct"] = summary["Actual"] == summary["Predicted"]
st.dataframe(summary.reset_index(drop=True), use_container_width=True, height=300)

st.success("Evaluation complete. No model retraining was performed on the uploaded test data.")
